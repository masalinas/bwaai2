import { http, HttpResponse } from 'msw';
import type {
  DocumentDetailResponse,
  DocumentListResponse,
  DocumentStatusResponse,
  DocumentUploadItem,
} from '../../src/api/types';

export const mockInitialList: DocumentListResponse = {
  items: [
    {
      document_id: 'doc_existing_1',
      filename: 'existing_document.pdf',
      parser: 'pypdf',
      status: 'done',
      created_at: '2026-10-31T00:00:00Z',
      updated_at: '2026-10-31T00:01:00Z',
    },
  ],
  next_cursor: 'cursor_page_2',
  has_more: true,
};

export const mockPage2List: DocumentListResponse = {
  items: [
    {
      document_id: 'doc_existing_2',
      filename: 'older_document.pdf',
      parser: 'gemini',
      status: 'done',
      created_at: '2026-10-30T12:00:00Z',
      updated_at: '2026-10-30T12:02:00Z',
    },
  ],
  next_cursor: null,
  has_more: false,
};

export const handlers = [
  // List documents (supports cursor)
  http.get('*/api/documents', ({ request }) => {
    const url = new URL(request.url);
    const cursor = url.searchParams.get('cursor');
    if (cursor === 'cursor_page_2') {
      return HttpResponse.json(mockPage2List);
    }
    return HttpResponse.json(mockInitialList);
  }),

  // Upload documents
  http.post('*/api/documents', async ({ request }) => {
    const formData = await request.formData();
    const parser = (formData.get('parser') as string) || 'pypdf';
    const files = formData.getAll('files') as File[];

    if (parser === 'mistral') {
      return HttpResponse.json(
        {
          code: 'PARSER_UNAVAILABLE',
          message: "The requested parser 'mistral' is temporarily unavailable.",
          details: { service: 'mistral_parser' },
        },
        { status: 500 }
      );
    }

    const items: DocumentUploadItem[] = files.map((file, idx) => ({
      document_id: `doc_uploaded_${Date.now()}_${idx + 1}`,
      filename: file.name,
      status: 'queued',
    }));

    return HttpResponse.json(items, { status: 202 });
  }),

  // Status endpoint
  http.get('*/api/documents/:id/status', ({ params }) => {
    const id = params.id as string;
    const response: DocumentStatusResponse = {
      document_id: id,
      status: 'done',
      created_at: '2026-10-31T00:00:00Z',
      updated_at: '2026-10-31T00:00:05Z',
      error: null,
    };
    return HttpResponse.json(response);
  }),

  // Detail endpoint
  http.get('*/api/documents/:id', ({ params }) => {
    const id = params.id as string;
    const response: DocumentDetailResponse = {
      document_id: id,
      filename: 'document.pdf',
      parser: 'gemini',
      status: 'done',
      created_at: '2026-10-31T00:00:00Z',
      updated_at: '2026-10-31T00:00:05Z',
      summary: 'Executive summary generated by Gemini.',
      pages: [
        {
          page_number: 1,
          content: '# Page 1 Heading\n\nPage 1 parsed content.',
          format: 'markdown',
        },
        {
          page_number: 2,
          content: '# Page 2 Heading\n\nPage 2 parsed content.',
          format: 'markdown',
        },
      ],
      error: null,
    };
    return HttpResponse.json(response);
  }),
];
